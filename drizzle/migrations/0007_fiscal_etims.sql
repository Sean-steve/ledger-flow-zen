-- Phase 4: local PostgreSQL fiscalisation evidence boundary.
-- This is NOT a certified OSCU implementation or a KRA-approved device.
-- The local UI cannot assert successful KRA fiscalisation.
CREATE UNIQUE INDEX IF NOT EXISTS documents_business_id_id_fiscal_idx
  ON public.documents(business_id,id);
CREATE TABLE public.fiscal_profiles (
  business_id uuid PRIMARY KEY REFERENCES public.businesses(id) ON DELETE CASCADE,
  solution text NOT NULL DEFAULT 'OSCU' CHECK (solution='OSCU'),
  branch_id text NOT NULL DEFAULT '00',
  device_serial text,
  tax_mapping jsonb NOT NULL DEFAULT '{}'::jsonb,
  certification_state text NOT NULL DEFAULT 'UNVERIFIED'
    CHECK (certification_state='UNVERIFIED'),
  updated_by uuid NOT NULL,
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT fiscal_branch_id_format CHECK (branch_id ~ '^[0-9]{2,4}$'),
  CONSTRAINT fiscal_device_serial_format CHECK
    (device_serial IS NULL OR device_serial ~ '^[A-Za-z0-9_./-]{3,80}$')
);
ALTER TABLE public.fiscal_profiles ENABLE ROW LEVEL SECURITY;
GRANT SELECT ON public.fiscal_profiles TO authenticated;
GRANT SELECT,INSERT,UPDATE,DELETE ON public.fiscal_profiles TO service_role;
CREATE POLICY "fiscal profiles membership read"
 ON public.fiscal_profiles FOR SELECT TO authenticated
 USING (public.has_business_access(business_id));

CREATE TABLE public.fiscal_submissions (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  business_id uuid NOT NULL,
  document_id uuid NOT NULL,
  mode text NOT NULL CHECK (mode IN ('PREVIEW','SANDBOX')),
  solution text NOT NULL DEFAULT 'OSCU' CHECK (solution='OSCU'),
  status text NOT NULL CHECK (status IN
    ('PREVIEW','IN_FLIGHT','SANDBOX_ACKNOWLEDGED','REJECTED','UNKNOWN')),
  request_key uuid NOT NULL,
  snapshot jsonb NOT NULL,
  snapshot_sha256 text NOT NULL CHECK (snapshot_sha256 ~ '^[a-f0-9]{64}$'),
  bridge_ref text,
  sandbox_scu_id text,
  sandbox_receipt_number text,
  sandbox_internal_data text,
  sandbox_signature text,
  error_code text,
  requested_by uuid NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  completed_at timestamptz,
  updated_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE(business_id,request_key),
  UNIQUE(business_id,document_id,mode),
  FOREIGN KEY (business_id,document_id)
    REFERENCES public.documents(business_id,id) ON DELETE RESTRICT,
  CONSTRAINT fiscal_preview_never_ack CHECK
    (mode <> 'PREVIEW' OR
     (status = 'PREVIEW' AND bridge_ref IS NULL AND sandbox_scu_id IS NULL AND
      sandbox_receipt_number IS NULL AND sandbox_signature IS NULL)),
  CONSTRAINT fiscal_sandbox_ack_complete CHECK
    (status <> 'SANDBOX_ACKNOWLEDGED' OR
     (mode = 'SANDBOX' AND sandbox_scu_id IS NOT NULL AND
      sandbox_receipt_number IS NOT NULL AND sandbox_signature IS NOT NULL))
);
CREATE INDEX fiscal_submissions_business_recent_idx
 ON public.fiscal_submissions(business_id,created_at DESC);
ALTER TABLE public.fiscal_submissions ENABLE ROW LEVEL SECURITY;
GRANT SELECT ON public.fiscal_submissions TO authenticated;
GRANT SELECT,INSERT,UPDATE ON public.fiscal_submissions TO service_role;
CREATE POLICY "fiscal submissions member read"
 ON public.fiscal_submissions FOR SELECT TO authenticated
 USING (public.has_business_access(business_id));

CREATE TABLE public.fiscal_events (
  id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  business_id uuid NOT NULL REFERENCES public.businesses(id) ON DELETE CASCADE,
  submission_id uuid NOT NULL REFERENCES public.fiscal_submissions(id) ON DELETE CASCADE,
  event_type text NOT NULL CHECK (event_type IN
    ('PREVIEW_CREATED','SANDBOX_SUBMITTED','SANDBOX_ACKNOWLEDGED',
     'SANDBOX_REJECTED','SANDBOX_UNKNOWN')),
  created_at timestamptz NOT NULL DEFAULT now(),
  actor_id uuid NOT NULL,
  details jsonb NOT NULL DEFAULT '{}'::jsonb
);
CREATE INDEX fiscal_events_submission_idx ON public.fiscal_events(submission_id,created_at);
ALTER TABLE public.fiscal_events ENABLE ROW LEVEL SECURITY;
GRANT SELECT ON public.fiscal_events TO authenticated;
GRANT SELECT,INSERT ON public.fiscal_events TO service_role;
CREATE POLICY "fiscal events member read"
 ON public.fiscal_events FOR SELECT TO authenticated
 USING (public.has_business_access(business_id));
-- No direct INSERT/UPDATE/DELETE grants to authenticated users.
-- No production status code or KRA identity is generated by this schema.
